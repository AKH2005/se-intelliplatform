"""Vendor-Neutral Abstract LLM Provider Interfaces and DTOs."""

from abc import ABC, abstractmethod
from typing import Any, Literal, TypeVar
from pydantic import BaseModel, ConfigDict, Field

T = TypeVar("T", bound=BaseModel)


class LLMMessage(BaseModel):
    """Normalized message representation for prompt conversations."""

    role: Literal["system", "user", "assistant"] = Field(..., description="Message author role")
    content: str = Field(..., description="Text content of the message")


class LLMRequest(BaseModel):
    """Vendor-independent invocation parameters sent to an LLM provider."""

    messages: list[LLMMessage] = Field(..., min_length=1, description="Ordered conversation history")
    model: str = Field(..., description="Target model identifier (e.g. 'gemini-1.5-pro', 'gpt-4o')")
    temperature: float = Field(default=0.2, ge=0.0, le=2.0, description="Sampling randomness")
    max_tokens: int | None = Field(default=None, gt=0, description="Maximum token budget for output")
    metadata: dict[str, Any] = Field(default_factory=dict, description="Contextual execution metadata")


class LLMResponse(BaseModel):
    """Raw generation response returned by an LLM provider."""

    model_config = ConfigDict(arbitrary_types_allowed=True)

    content: str = Field(..., description="Text generated by the model")
    raw_metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Provider-specific token metrics or execution details (no credentials)",
    )


class AbstractLLMProvider(ABC):
    """Vendor-neutral contract for language model providers.
    
    All platform agents depend on this abstraction rather than proprietary vendor SDKs.
    """

    @property
    @abstractmethod
    def provider_name(self) -> str:
        """Name of the provider implementation (e.g. 'mock', 'gemini', 'openai')."""
        pass

    @property
    @abstractmethod
    def default_model(self) -> str:
        """Default model identifier for this provider."""
        pass

    @property
    def last_usage_metadata(self) -> dict[str, Any] | None:
        """Token usage and execution telemetry from the most recent request (if available)."""
        return getattr(self, "_last_usage_metadata", None)

    @last_usage_metadata.setter
    def last_usage_metadata(self, value: dict[str, Any] | None) -> None:
        self._last_usage_metadata = value



    @abstractmethod
    async def generate(self, request: LLMRequest) -> LLMResponse:
        """Execute a text generation request."""
        pass

    @abstractmethod
    async def generate_structured(
        self,
        request: LLMRequest,
        response_model: type[T],
    ) -> T:
        """Generate and parse structured data adhering directly to a Pydantic schema."""
        pass
