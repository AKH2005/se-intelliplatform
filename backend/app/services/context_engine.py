"""Project Context Engine & Deterministic Snapshot Management.

This module implements the canonical context layer for SE IntelliPlatform.
All future SDLC intelligence agents consume structured context generated by
this engine rather than independently reconstructing state from raw tables.

Context Inclusion Rules:
- DRAFT = included
- APPROVED = included
- IMPLEMENTED = included
- DEFERRED = excluded
- REJECTED = excluded
- is_archived = True is excluded

Deterministic Completion Calculation:
- active_requirements = DRAFT + APPROVED + IMPLEMENTED
- completion_percentage = (IMPLEMENTED / active_requirements) * 100.0
- if active_requirements == 0: completion_percentage = 0.0
"""

import logging
import uuid
from datetime import datetime, timezone
from typing import Sequence
from sqlalchemy import func, select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.exceptions import ConflictError, NotFoundError
from app.models.context_snapshot import ContextSnapshot
from app.models.project import Project
from app.models.requirement import (
    Requirement,
    RequirementPriority,
    RequirementStatus,
    RequirementType,
)
from app.schemas.context import (
    ProjectContextResponse,
    RequirementStatistics,
)
from app.schemas.project import ProjectResponse
from app.schemas.requirement import RequirementResponse

logger = logging.getLogger(__name__)

# Canonical status sets
INCLUDED_STATUSES = {
    RequirementStatus.DRAFT,
    RequirementStatus.APPROVED,
    RequirementStatus.IMPLEMENTED,
}
EXCLUDED_STATUSES = {
    RequirementStatus.DEFERRED,
    RequirementStatus.REJECTED,
}


class ProjectContextEngine:
    """Canonical engine assembling deterministic project context and versioned snapshots."""

    def __init__(self, session: AsyncSession) -> None:
        self.session = session

    async def _get_project(self, project_id: uuid.UUID) -> Project:
        """Fetch project by ID or raise NotFoundError."""
        statement = select(Project).where(Project.id == project_id)
        result = await self.session.execute(statement)
        project = result.scalar_one_or_none()
        if not project:
            raise NotFoundError(resource_type="Project", identifier=project_id)
        return project

    def calculate_statistics(
        self,
        all_requirements: Sequence[Requirement],
    ) -> tuple[RequirementStatistics, list[Requirement]]:
        """Compute deterministic statistics strictly adhering to Phase 2 rules.
        
        Returns:
            Tuple of (calculated RequirementStatistics, list of active eligible Requirements)
        """
        # Filter active non-archived eligible requirements
        eligible_requirements: list[Requirement] = []
        status_counts = {s.value: 0 for s in RequirementStatus}
        priority_counts = {p.value: 0 for p in RequirementPriority}

        functional_count = 0
        non_functional_count = 0
        constraint_count = 0
        implemented_count = 0

        for req in all_requirements:
            # Tally total status distribution (including archived/deferred/rejected for audits)
            status_counts[req.status.value] = status_counts.get(req.status.value, 0) + 1

            # Check inclusion rules for active canonical context
            if not req.is_archived and req.status in INCLUDED_STATUSES:
                eligible_requirements.append(req)
                priority_counts[req.priority.value] = priority_counts.get(req.priority.value, 0) + 1

                if req.type == RequirementType.FUNCTIONAL:
                    functional_count += 1
                elif req.type == RequirementType.NON_FUNCTIONAL:
                    non_functional_count += 1
                elif req.type == RequirementType.CONSTRAINT:
                    constraint_count += 1

                if req.status == RequirementStatus.IMPLEMENTED:
                    implemented_count += 1

        active_count = len(eligible_requirements)
        total_recorded = len(all_requirements)

        # Deterministic completion calculation:
        # active_requirements = DRAFT + APPROVED + IMPLEMENTED
        # completion_percentage = (IMPLEMENTED / active_requirements) * 100.0
        # If active_requirements == 0: completion_percentage = 0.0
        if active_count > 0:
            completion_percentage = round((implemented_count / active_count) * 100.0, 2)
        else:
            completion_percentage = 0.0

        stats = RequirementStatistics(
            total_requirements=total_recorded,
            active_requirements=active_count,
            functional_count=functional_count,
            non_functional_count=non_functional_count,
            constraint_count=constraint_count,
            by_priority=priority_counts,
            by_status=status_counts,
            completion_percentage=completion_percentage,
        )

        return stats, eligible_requirements

    async def get_latest_version_number(self, project_id: uuid.UUID) -> int:
        """Query highest snapshot version recorded for project, default 0."""
        stmt = select(func.coalesce(func.max(ContextSnapshot.version), 0)).where(
            ContextSnapshot.project_id == project_id
        )
        return (await self.session.execute(stmt)).scalar_one()

    async def generate_context(self, project_id: uuid.UUID) -> ProjectContextResponse:
        """Assemble canonical, validated Project Context representing current project state."""
        project = await self._get_project(project_id)

        # Query all requirements belonging to project
        stmt = (
            select(Requirement)
            .where(Requirement.project_id == project_id)
            .order_by(Requirement.created_at.desc())
        )
        requirements = (await self.session.execute(stmt)).scalars().all()

        statistics, eligible_reqs = self.calculate_statistics(requirements)
        current_version = await self.get_latest_version_number(project_id)

        response = ProjectContextResponse(
            project=ProjectResponse.model_validate(project),
            requirements=[RequirementResponse.model_validate(r) for r in eligible_reqs],
            statistics=statistics,
            context_version=current_version,
            generated_at=datetime.now(timezone.utc),
        )

        logger.info(
            f"Generated canonical project context for project [id={project_id}], "
            f"active_reqs={statistics.active_requirements}, completion={statistics.completion_percentage}%"
        )
        return response

    async def create_snapshot(
        self,
        project_id: uuid.UUID,
        summary: str | None = None,
        max_retries: int = 3,
    ) -> ContextSnapshot:
        """Create an immutable, versioned snapshot of the canonical Project Context.
        
        Handles snapshot version concurrency deterministically: if a concurrent process
        claims version N, retries with the newly updated sequence number.
        """
        for attempt in range(max_retries):
            # Generate current context
            context = await self.generate_context(project_id)

            # Determine next version sequence
            latest_version = await self.get_latest_version_number(project_id)
            new_version = latest_version + 1

            # Update context_version within the payload to reflect this new snapshot version
            context_payload = context.model_dump(mode="json")
            context_payload["context_version"] = new_version

            snapshot = ContextSnapshot(
                project_id=project_id,
                version=new_version,
                context_data=context_payload,
                summary=summary,
            )

            self.session.add(snapshot)
            try:
                await self.session.commit()
                await self.session.refresh(snapshot)
                logger.info(
                    f"Created immutable ContextSnapshot v{snapshot.version} "
                    f"[id={snapshot.id}] for project [id={project_id}]"
                )
                return snapshot
            except IntegrityError as exc:
                await self.session.rollback()
                logger.warning(
                    f"Concurrency collision creating snapshot v{new_version} for "
                    f"project [id={project_id}] on attempt {attempt + 1}: {exc}"
                )
                if attempt == max_retries - 1:
                    raise ConflictError(
                        message=f"Concurrent snapshot creation collision for project '{project_id}'.",
                    ) from exc

        raise ConflictError(
            message=f"Failed to create snapshot for project '{project_id}' after retries."
        )

    async def get_snapshot_by_version(
        self,
        project_id: uuid.UUID,
        version: int,
    ) -> ContextSnapshot:
        """Retrieve a specific historical snapshot by project ID and version."""
        await self._get_project(project_id)

        statement = select(ContextSnapshot).where(
            ContextSnapshot.project_id == project_id,
            ContextSnapshot.version == version,
        )
        result = await self.session.execute(statement)
        snapshot = result.scalar_one_or_none()
        if not snapshot:
            raise NotFoundError(
                resource_type="ContextSnapshot",
                identifier=f"version {version} on project {project_id}",
            )
        return snapshot

    async def list_snapshots(
        self,
        project_id: uuid.UUID,
        skip: int = 0,
        limit: int = 50,
    ) -> tuple[Sequence[ContextSnapshot], int]:
        """List historical snapshots for a project ordered by version descending."""
        await self._get_project(project_id)

        query = (
            select(ContextSnapshot)
            .where(ContextSnapshot.project_id == project_id)
            .order_by(ContextSnapshot.version.desc())
            .offset(skip)
            .limit(limit)
        )
        count_query = (
            select(func.count())
            .select_from(ContextSnapshot)
            .where(ContextSnapshot.project_id == project_id)
        )

        total_count = (await self.session.execute(count_query)).scalar_one()
        results = (await self.session.execute(query)).scalars().all()

        return results, total_count
